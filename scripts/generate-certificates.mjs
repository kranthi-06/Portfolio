import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const assetsRoot = path.join(root, "public", "assets");
const output = path.join(root, "lib", "generated-certificates.ts");

const extensions = new Set([".png", ".jpg", ".jpeg", ".webp", ".pdf"]);
const categories = [
  [["internship"], "Internships"],
  [["certificate", "certification", "license"], "Certifications"],
  [["course", "cource"], "Courses"],
  [["workshop"], "Workshops"],
  [["webinar", "webniar"], "Webinars"],
  [["hackathon"], "Hackathons"],
  [["training", "bootcamp"], "Training Programs"],
  [["achievement"], "Achievements"],
  [["badge"], "Badges"],
];

function normalise(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
}

function categoryFor(relativePath) {
  // The nearest category folder wins: /certificates/courses/power-bi belongs to Courses,
  // not the generic parent directory named certificates.
  const folders = path.dirname(relativePath).split(path.sep).reverse().map(normalise);
  for (const folder of folders) {
    const found = categories.find(([terms]) => terms.some((term) => folder.includes(term)));
    if (found) return found[1];
  }
  return "Others";
}

function titleFor(filename) {
  return path
    .basename(filename, path.extname(filename))
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function organisationFor(title) {
  const providers = [
    "IBM", "Simplilearn", "SimpleLearn", "GeeksforGeeks", "Deloitte", "Analytics Vidhya",
    "SkillsBuild", "Microsoft Learn", "GUVI", "HCL", "Scaler", "Pantech", "Ewayte",
    "Yuga Yatra", "Edvedha", "Elite Coders", "Kitech", "APSCHE", "SREC",
  ];
  return providers.find((provider) => title.toLowerCase().includes(provider.toLowerCase())) ?? "Professional learning";
}

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (entry.name.startsWith(".") || entry.name === "Thumbs.db" || entry.name === "Desktop.ini") continue;
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(fullPath));
    else if (entry.isFile()) files.push(fullPath);
  }

  return files;
}

const assetFiles = await walk(assetsRoot);
const certificates = assetFiles
  .map((file) => ({ file, relative: path.relative(assetsRoot, file) }))
  .filter(({ relative }) => {
    const extension = path.extname(relative).toLowerCase();
    const filename = path.basename(relative);
    const isInCertificateArea = categories.some(([terms]) => terms.some((term) => normalise(relative).includes(term)));
    // Exclude education-provider artefacts explicitly marked as EDU, regardless of
    // whether EDU appears at the beginning or within a longer filename.
    return extensions.has(extension) && isInCertificateArea && !/\bedu\b/i.test(filename);
  })
  .map(({ relative }) => {
    const title = titleFor(relative);
    return {
      id: relative.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, ""),
      title,
      category: categoryFor(relative),
      organisation: organisationFor(title),
      src: `/assets/${relative.split(path.sep).map(encodeURIComponent).join("/")}`,
      type: path.extname(relative).slice(1).toLowerCase() === "pdf" ? "pdf" : "image",
    };
  })
  .sort((a, b) => a.category.localeCompare(b.category) || a.title.localeCompare(b.title));

const generated = `/* This file is generated by scripts/generate-certificates.mjs. Do not edit manually. */\n\nexport type CertificateAsset = {\n  id: string;\n  title: string;\n  category: string;\n  organisation: string;\n  src: string;\n  type: "image" | "pdf";\n};\n\nexport const certificateAssets: CertificateAsset[] = ${JSON.stringify(certificates, null, 2)};\n`;
await writeFile(output, generated);
console.log(`Generated ${certificates.length} certificate records.`);
